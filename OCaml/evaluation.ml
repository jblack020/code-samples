 module type ENV = sig
     (* the type of environments *)
     type env and 
            
     (* the type of values (including closures) stored in
        environments *)
     value =
       | Val of expr
       | Closure of (expr * env)
          
     (* empty () -- Returns an empty environment *)
     val empty : unit -> env
 
     (* close expr env -- Returns a closure for `expr` and its `env` *)
     val close : expr -> env -> value
 
     (* lookup env varid -- Returns the value in the `env` for the
        `varid`, raising an `Eval_error` if not found *)
     val lookup : env -> varid -> value
 
     (* extend env varid loc -- Returns a new environment just like
        `env` except that it maps the variable `varid` to the `value`
        stored at `loc`. This allows later changing the value, an
        ability used in the evaluation of `letrec`. To make good on
        this, extending an environment needs to preserve the previous
        bindings in a physical, not just structural, way. *)
     val extend : env -> varid -> value ref -> env

     (* Returns the underlying expression within the value *)
     val unwrap : value -> expr
 
     (* env_to_string env -- Returns a printable string representation
        of environment `env` *)
     val env_to_string : env -> string
                                  
     (* value_to_string ?printenvp value -- Returns a printable string
        representation of a value; the optional flag `printenvp`
        (default: `true`) determines whether to include the environment
        in the string representation when called on a closure *)
     val value_to_string : ?printenvp:bool -> value -> string
   end
 
 module Env : ENV =
   struct
     type env = (varid * value ref) list
      and value =
        | Val of expr
        | Closure of (expr * env)
 
     let empty () : env = []

     let close (exp : expr) (env : env) : value =
       Closure (exp, env)
 
     let rec lookup (env : env) (varname : varid) : value =
       match env with 
       | [] -> raise (EvalError "Cannot lookup in empty environment")
       | (var, value_ref) :: tl -> 
           if var = varname then !value_ref else lookup tl varname 
           
     let rec extend (env : env) (varname : varid) (loc : value ref) : env =
       match env with 
       | [] -> [varname, loc]
       | (var, _) as hd :: tl -> 
         if var = varname then (varname, loc) :: tl 
         else hd :: extend tl varname loc  
      
      let unwrap (v : value) : expr =
        match v with 
        | Val exp -> exp
        | Closure (exp, _) -> exp
 
     let rec value_to_string ?(printenvp : bool = true) (v : value) : string =
       match v with 
       | Val exp -> exp_to_concrete_string exp
       | Closure (exp, environment) -> 
         if printenvp 
           then "{" ^ env_to_string environment ^ "} ⊢ " ^ 
                exp_to_concrete_string exp
         else exp_to_concrete_string exp
 
     and env_to_string (env : env) : string =
       let tuple_format (var, value_ref) = 
         var ^ " ↦ " ^ value_to_string !value_ref in
       (String.concat (", ") (List.map tuple_format env))  
   end
 ;; 

type evaluator = expr -> Env.env -> Env.value

let eval_t (exp : expr) (_env : Env.env) : Env.value =
  (* coerce the expr, unchanged, into a value *)
  Env.Val exp ;;

module type EVAL_PARAMS = 
  sig
    open Env ;;
    val evaluate_fun : expr -> env -> evaluator -> value
    val evaluate_app : expr -> expr -> env -> evaluator -> value
    val evaluate_var : varid -> env -> evaluator -> value
    val evaluate_let : varid -> expr -> expr -> env -> evaluator -> value
    val evaluate_letrec : varid -> expr -> expr -> env -> evaluator -> value
  end

module type EVAL = 
  sig
    val eval : expr -> Env.env -> Env.value
  end


module EvalGenerator (P: EVAL_PARAMS) : EVAL = 
  struct
    let rec eval (exp : expr) (envr : Env.env) : Env.value =
      (* Helper function to determine whether item is of same type as list *)
      let same_type (e : expr) (lst : expr list) : bool =
        if lst = [] then true else (* Empty list has no type *)
        let get_type = function
        | Num _      -> "Num"       | Unit _     -> "Unit"
        | Bool _     -> "Bool"      | Unassigned -> "Unassigned"
        | Float _    -> "Float"     | Raise      -> "Raise"
        | String _   -> "String"    | Var _      -> "Var"
        | List _     -> "List"      | Fun _      -> "Fun"
        | _ -> raise (EvalError "Invalid list type") in
        List.for_all (fun x -> get_type (Env.unwrap (eval x envr)) = 
                               get_type (Env.unwrap (eval e envr))) lst 
      in

      (* Helper function to evaluate unary operations *)
      let evaluate_unop (op : unop) (e1 : expr) : Env.value =
        Val ( match Env.unwrap (eval e1 envr) with
              (* Int operations *)
              | Num n  -> (match op with 
                          | Negate -> Num (-n)
                          | _ -> raise (EvalError "Invalid unary op") )

              (* Bool operations *)
              | Bool b -> (match op with 
                          | Not -> Bool (not b)
                          | _ -> raise (EvalError "Invalid unary op") )
                          
              (* Float operations *)
              | Float f -> (match op with 
                          | FloatNegate -> Float (-.f)
                          | FloatCeil   -> Float (ceil f)
                          | FloatFloor  -> Float (floor f)
                          | FloatRound  -> Float (floor (f +. 0.5))
                          | FloatSqrt   -> Float (sqrt f)
                          | Sin         -> Float (sin f)
                          | Cos         -> Float (cos f)
                          | Tan         -> Float (tan f)
                          | _ -> raise (EvalError "Invalid unary op") )
              
              (* String operations *)
              | String s -> (match op with 
                          | StringLength -> Num (String.length s)
                          | _ -> raise (EvalError "Invalid unary op") )
              
              (* List operations *)
              | List l -> (match op with 
                          | ListLength -> Num (List.length l)
                          | Head -> if l <> [] then List.hd l else 
                              raise (EvalError "Head of empty list")
                          | Tail -> if l <> [] then List (List.tl l)
                              else raise (EvalError "Tail of empty list")
                          | IsEmpty -> Bool (List.length l = 0)
                          | _ -> raise (EvalError "Invalid unary op") )

              | _ -> raise (EvalError "Invalid unary op") ) in
      
      (* Helper function to evaluate binary operations *)
      let evaluate_binop (op : binop) (e1 : expr) (e2 : expr) : Env.value = 
        Val ( 
          match Env.unwrap (eval e1 envr), Env.unwrap (eval e2 envr) with
            (* Int operations *)
            | Num n1, Num n2   -> (match op with 
                                  | Plus        -> Num  (n1 + n2)
                                  | Minus       -> Num  (n1 - n2)
                                  | Times       -> Num  (n1 * n2)
                                  | Divide      -> Num  (n1 / n2)
                                  | Mod         -> Num  (n1 mod n2)
                                  | LessThan    -> Bool (n1 < n2)
                                  | GreaterThan -> Bool (n1 > n2)
                                  | Equals      -> Bool (n1 = n2) 
                                  | _ -> raise (EvalError "Invalid binaryop"))

            (* Bool operations *)                      
            | Bool b1, Bool b2 -> (match op with 
                                  | Equals      -> Bool (b1 = b2)
                                  | LessThan    -> Bool (b1 < b2)
                                  | GreaterThan -> Bool (b1 > b2)
                                  | And         -> Bool (b1 && b2)
                                  | Or          -> Bool (b1 || b2)
                                  | _ -> raise (EvalError "Invalid binaryop"))
            (* Float operations *)
            | Float f1, Float f2 -> (match op with 
                                  | FloatPlus   -> Float (f1 +. f2)
                                  | FloatMinus  -> Float (f1 -. f2)
                                  | FloatTimes  -> Float (f1 *. f2)
                                  | FloatDivide -> Float (f1 /. f2)
                                  | FloatMod    -> Float (mod_float f1 f2)
                                  | Equals      -> Bool  (f1 = f2)
                                  | LessThan    -> Bool  (f1 < f2)
                                  | GreaterThan -> Bool  (f1 > f2)
                                  | _ -> raise (EvalError "Invalid binaryop"))

            (* String operations *)
            | String s1, String s2 -> (match op with 
                                  | StringConcat -> String (s1 ^ s2)
                                  | Equals       -> Bool   (s1 = s2)
                                  | LessThan     -> Bool   (s1 < s2)
                                  | GreaterThan  -> Bool   (s1 > s2)
                                  | _ -> raise (EvalError "Invalid binaryop"))
              
            (* List operations *)
            | List l1, List l2 -> if (l1 = [] || same_type (List.hd l1) l2) then 
                                  (match op with 
                                  | Append       -> List (l1 @ l2)
                                  | Equals       -> Bool (l1 = l2)
                                  | LessThan     -> Bool (l1 < l2)
                                  | GreaterThan  -> Bool (l1 > l2)
                                  | _ -> raise (EvalError "Invalid binary op"))
                                  else raise 
                                    (EvalError "List1, List2 must be same type")  

            | elt, List l      -> if (same_type (Env.unwrap (eval elt envr)) l)  
                                  then (match op with
                                  | Cons -> List (elt :: l)
                                  | _ -> raise (EvalError "Invalid binary op") )
                                  else raise 
                                    (EvalError "List, elt must be same type") 

            | _ -> raise (EvalError "Invalid binary op") ) in

    
      (* Helper function to evaluate conditionals *)
      let evaluate_conditional (condition : expr) (true_branch : expr) 
                               (false_branch : expr) : Env.value =
        match Env.unwrap (eval condition envr) with 
        | Bool b -> if b then eval true_branch envr else eval false_branch envr 
        | _ -> raise (EvalError "Invalid conditional") in
      
      let evaluate_lists (lst : expr list) : expr list = 
        if (lst = [] || same_type (List.hd lst) lst) then
          List.map (fun x -> Env.unwrap (eval x envr)) lst 
        else raise (EvalError "List elements must be same type") in

      (* Main eval using above static helper funcs & dynamic P module funcs *)
      match exp with 
      | Num n                        -> Val (Num n)
      | Bool b                       -> Val (Bool b)
      | Float f                      -> Val (Float f)
      | String s                     -> Val (String s)
      | Unit ()                      -> Val (Unit ())
      | Unassigned                   -> raise (EvalError "Unassigned evaluate")
      | Raise                        -> raise EvalException
      | Unop (operation, e1)         -> evaluate_unop operation e1
      | Binop (operation, e1, e2)    -> evaluate_binop operation e1 e2 
      | Conditional (cond, e1, e2)   -> evaluate_conditional cond e1 e2 
      | List l                       -> Val (List (evaluate_lists l)) 
      | Var v                        -> P.evaluate_var v envr eval
      | Fun (_, _)                   -> P.evaluate_fun exp envr eval
      | App (func, arg)              -> P.evaluate_app func arg envr eval
      | Let (name, def, body)        -> P.evaluate_let name def body envr eval
      | Letrec (name, def, body)     -> P.evaluate_letrec name def body envr eval
  end

(* Argument for substitution evaluation *)
module Eval_s : EVAL_PARAMS = 
  struct
    let evaluate_fun (exp : expr) (_env : Env.env) 
                      (_eval : evaluator) : Env.value = 
      Val exp

    let evaluate_app (func : expr) (arg : expr) (env : Env.env) 
                     (eval : expr -> Env.env -> Env.value) : Env.value =
      let func_eval = Env.unwrap (eval func env) in 
      let arg_eval = Env.unwrap (eval arg env) in 
      match func_eval with 
      | Fun (arg_name, body) -> eval (subst arg_name arg_eval body) env
      | _ -> raise (EvalError "Arg is not a function, it cannot be applied")

    let evaluate_var (v : varid) (_env : Env.env) 
                     (_eval : evaluator) : Env.value = 
      raise (EvalError ("Unbound value " ^ v))
    
    let evaluate_let (name : varid) (def : expr) (body : expr) (env : Env.env)
                     (eval : expr -> Env.env -> Env.value) : Env.value =
      let def_eval = Env.unwrap (eval def env) in 
      let body_sub = subst name def_eval body in
      eval body_sub env
    
    let evaluate_letrec (name : varid) (def : expr) (body : expr) 
                        (env : Env.env) (eval : expr -> Env.env -> Env.value) 
                        : Env.value =
      let def_eval = Env.unwrap (eval def env) in
      let def_sub = subst name (Letrec (name, def_eval, Var (name))) def_eval 
      in eval (subst name def_sub body) env
  end

(* Argument for dynamic environmental evaluation *)
module Eval_d : EVAL_PARAMS = 
  struct
    let evaluate_fun (exp : expr) (_env : Env.env) 
                     (_eval : evaluator) : Env.value = 
      Val exp

    let evaluate_app (func : expr) (arg : expr) (env : Env.env) 
                     (eval : evaluator) : Env.value = 
      let func_eval = Env.unwrap (eval func env) in 
      let arg_eval = eval arg env in 
      match func_eval with 
      | Fun (arg_name, body) -> 
          eval body (Env.extend env arg_name (ref arg_eval))
      | _ -> raise (EvalError "Arg is not a function, it cannot be applied")
    
    let evaluate_var (v : varid) (env : Env.env) 
                     (_eval : evaluator) : Env.value = 
      Env.lookup env v

    let evaluate_let (name : varid) (def : expr) (body : expr) (env : Env.env) 
                     (eval : evaluator) : Env.value =
      let def_eval = eval def env in 
      eval body (Env.extend env name (ref def_eval))
    
    let evaluate_letrec = evaluate_let 
  end
  
(* Argument for lexical environmental evaluation *)
module Eval_l : EVAL_PARAMS = 
  struct
    let evaluate_fun (exp : expr) (env : Env.env) 
                     (_eval : evaluator) : Env.value = 
      Closure (exp, env)

    let evaluate_app (func : expr) (arg : expr) (env : Env.env) 
                     (eval : evaluator) : Env.value = 
      let func_eval = eval func env in 
      let arg_eval = eval arg env in 
      match func_eval with 
      | Closure (Fun (arg_name, body), closure_env) -> 
          eval body (Env.extend closure_env arg_name (ref arg_eval))
      | _ -> raise (EvalError "Arg is not a function, it cannot be applied")

    (* Evaluation of variables and let statements is the same as Eval_d *)
    let evaluate_var = Eval_d.evaluate_var  
    let evaluate_let = Eval_d.evaluate_let 

    let evaluate_letrec (name : varid) (def : expr) (body : expr) 
                        (env : Env.env) (eval : evaluator) : Env.value =
      let placeholder = ref (Env.Val Unassigned) in 
      let new_env = Env.extend env name placeholder in 
      let def_eval = eval def new_env in 
      placeholder := def_eval;
      (* Check to make sure the placeholder still is not unassigned *)
      if placeholder <> ref (Env.Val Unassigned) then 
        eval body new_env
      else raise 
        (EvalError 
          "This kind of expression is not allowed as right-hand side of let rec"
        )
  end

module Eval_s_module = EvalGenerator(Eval_s) ;;
module Eval_d_module = EvalGenerator(Eval_d) ;;
module Eval_l_module = EvalGenerator(Eval_l) ;;

let eval_s = Eval_s_module.eval;;
let eval_d = Eval_d_module.eval;;  
let eval_l = Eval_l_module.eval;;
let evaluate = eval_l ;;